function Initializelogger {

    Write-NovoraInfo "Inicializando NOVORA..."

    #--------------------------------------------------------
    # Logger
    #--------------------------------------------------------

    Initialize-Logger

    #--------------------------------------------------------
    # Configuración
    #--------------------------------------------------------

    Initialize-Config

    #--------------------------------------------------------
    # Engine
    #--------------------------------------------------------

    Initialize-NovoraEngine

    #--------------------------------------------------------
    # Verificar entorno
    #--------------------------------------------------------

    if (!(Start-NovoraChecks)) {

        Write-NovoraError "La verificación del sistema falló."

        return

    }

    #--------------------------------------------------------
    # Launcher
    #--------------------------------------------------------

    Initialize-NovoraLauncher

    #--------------------------------------------------------
    # Mostrar menú
    #--------------------------------------------------------

    Show-NovoraMenu

}