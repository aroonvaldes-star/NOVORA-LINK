using System.Net;
using System.Net.Sockets;
using NOVORA.Control;
using NOVORA.VisionEngine.Control;
using var lifetime=new CancellationTokenSource(TimeSpan.FromSeconds(10)); var ct=lifetime.Token;
using var listener=new TcpListener(IPAddress.Loopback,0); listener.Start();
using var pc=new TcpClient(); var connect=pc.ConnectAsync((IPEndPoint)listener.LocalEndpoint,ct);
using var android=await listener.AcceptTcpClientAsync(ct); await connect;
await using var manager=new VEControlManager(); await manager.StartNativeAsync(pc.GetStream(),ct);
var clipboard=new TaskCompletionSource<string>(TaskCreationOptions.RunContinuationsAsynchronously);
manager.ClipboardChangedVE+=(_,text)=>clipboard.TrySetResult(text);
var apply=manager.ApplyCapturePolicyAsync(new(42,7,1_000_000,30),ct);
var command=await NLControlProtocol.ReadAsync<NLControlInputCommand>(android.GetStream(),ct);
if(command.Type!=23 || command.CapturePolicy!=new NLControlCapturePolicy(42,7,1_000_000,30))throw new Exception("Capture payload lost in PC serializer");
await NLControlProtocol.WriteAsync(android.GetStream(),new NLControlInputResponse(1,"clipboard"),ct);
await NLControlProtocol.WriteAsync(android.GetStream(),new NLControlInputResponse(3,CapturePolicyAck:new(41,7,true,1_000_000,null)),ct);
await NLControlProtocol.WriteAsync(android.GetStream(),new NLControlInputResponse(3,CapturePolicyAck:new(42,7,true,2_000_000,null)),ct);
await Task.Delay(50,ct);
if(apply.IsCompleted)throw new Exception("ACK for another generation or requested bitrate completed current policy");
await NLControlProtocol.WriteAsync(android.GetStream(),new NLControlInputResponse(3,CapturePolicyAck:new(42,7,true,1_000_000,null)),ct);
var ack=await apply.WaitAsync(TimeSpan.FromSeconds(3),ct);
if(ack?.Accepted!=true || ack.ObservedBitrate is not null)throw new Exception("Matching ACK not received or invented observed bitrate");
if(await clipboard.Task.WaitAsync(TimeSpan.FromSeconds(3),ct)!="clipboard")throw new Exception("Unique reader lost clipboard during policy ACK");
var pending=manager.ApplyCapturePolicyAsync(new(42,8,1_000_000,30),ct);
await NLControlProtocol.ReadAsync<NLControlInputCommand>(android.GetStream(),ct);
await manager.StopAsync(ct);
if(await pending is not null)throw new Exception("Stopped generation confirmed old request");
Console.WriteLine("PASS actual PC capture serializer, unique clipboard/ACK reader, stale/mismatched replies, lifecycle cancellation");
